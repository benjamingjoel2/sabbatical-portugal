"""Build components/svg/portugalGeo.ts from Natural Earth 1:10m admin-0 countries (public domain).

Usage: python3 scripts/build-map.py path/to/ne_10m_admin_0_countries.geojson
"""
import json, math, sys, os

src = sys.argv[1]
d = json.load(open(src))

def polys(name):
    for f in d['features']:
        if f['properties'].get('ADMIN') == name:
            g = f['geometry']
            return g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
    raise SystemExit(name + ' not found')

def dp(pts, eps):
    if len(pts) < 3:
        return pts
    (ax, ay), (bx, by) = pts[0], pts[-1]
    L = math.hypot(bx - ax, by - ay)
    dmax, idx = 0, 0
    for i in range(1, len(pts) - 1):
        px, py = pts[i]
        dist = math.hypot(px - ax, py - ay) if L == 0 else abs((by - ay) * px - (bx - ax) * py + bx * ay - by * ax) / L
        if dist > dmax:
            dmax, idx = dist, i
    if dmax > eps:
        return dp(pts[: idx + 1], eps)[:-1] + dp(pts[idx:], eps)
    return [pts[0], pts[-1]]

def simplify_ring(xy, eps):
    # split closed ring in two so the endpoints differ
    m = len(xy) // 2
    return dp(xy[: m + 1], eps)[:-1] + dp(xy[m:], eps)

def proj(lon0, lat0, k, clat):
    c = math.cos(math.radians(clat))
    return lambda lon, lat: ((lon - lon0) * k * c, (lat0 - lat) * k)

def path(country, P, bbox, eps, min_pts=4):
    out = []
    for poly in country:
        ring = poly[0]
        lons = [p[0] for p in ring]; lats = [p[1] for p in ring]
        if max(lons) < bbox[0] or min(lons) > bbox[2] or max(lats) < bbox[1] or min(lats) > bbox[3]:
            continue
        xy = simplify_ring([P(*p) for p in ring], eps)
        if len(xy) < min_pts:
            continue
        out.append('M' + 'L'.join(f'{x:.1f} {y:.1f}' for x, y in xy) + 'Z')
    return ''.join(out)

pt, es = polys('Portugal'), polys('Spain')

K = 110
lon0, lat0, lon1, lat1 = -10.0, 42.3, -5.6, 36.75
Pm = proj(lon0, lat0, K, 39.5)
W, H = Pm(lon1, lat1)
mainland = path(pt, Pm, (-10.0, 36.5, -6.0, 42.5), 0.35)
spain = path(es, Pm, (-10.0, 35.5, -4.0, 43.5), 0.6)

Pmd = proj(-17.35, 33.15, 380, 32.8)
MW, MH = Pmd(-16.2, 32.35)
mad = path(pt, Pmd, (-17.4, 32.3, -16.0, 33.2), 0.3, 3)

Paz = proj(-31.4, 40.0, 72, 38.5)
AW, AH = Paz(-24.6, 36.8)
az = path(pt, Paz, (-31.5, 36.5, -24.5, 40.1), 0.12, 3)

places = {
    'lisbon': (-9.14, 38.72), 'porto': (-8.61, 41.15), 'cascais-sintra': (-9.40, 38.73), 'ericeira': (-9.42, 38.96),
    'comporta': (-8.79, 38.38), 'lagos-western-algarve': (-8.67, 37.10), 'tavira-eastern-algarve': (-7.65, 37.13),
    'evora-alentejo': (-7.91, 38.57), 'douro-valley': (-7.55, 41.19), 'coimbra': (-8.43, 40.21),
}
pins = {k: Pm(*v) for k, v in places.items()}
fx, fy = Pmd(-16.91, 32.65)
ax_, ay_ = Paz(-25.67, 37.74)

ts = f"""/**
 * Real geography for the Portugal map, generated by scripts/build-map.py from Natural Earth
 * 1:10m admin-0 countries (public domain, naturalearthdata.com), simplified for the web.
 * Equirectangular projection with latitude correction.
 */
export const MAINLAND_VIEW = {{ w: {W:.0f}, h: {H:.0f} }};
export const PORTUGAL_MAINLAND = '{mainland}';
export const SPAIN = '{spain}';
export const MADEIRA_VIEW = {{ w: {MW:.0f}, h: {MH:.0f} }};
export const MADEIRA = '{mad}';
export const AZORES_VIEW = {{ w: {AW:.0f}, h: {AH:.0f} }};
export const AZORES = '{az}';

/** Destination pins in their frame's coordinates, from real latitude/longitude. */
export const GEO_PINS: Record<string, {{ frame: 'mainland' | 'madeira' | 'azores'; x: number; y: number }}> = {{
""" + ''.join(f"  '{k}': {{ frame: 'mainland', x: {x:.1f}, y: {y:.1f} }},\n" for k, (x, y) in pins.items()) + f"""  madeira: {{ frame: 'madeira', x: {fx:.1f}, y: {fy:.1f} }},
  azores: {{ frame: 'azores', x: {ax_:.1f}, y: {ay_:.1f} }},
}};
"""
out = os.path.join(os.path.dirname(__file__), '..', 'components', 'svg', 'portugalGeo.ts')
open(out, 'w').write(ts)
print('path chars', len(mainland), len(spain), len(mad), len(az), 'views', round(W), round(H), round(MW), round(MH), round(AW), round(AH))
